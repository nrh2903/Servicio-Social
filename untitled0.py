# === 4. EVALUACIÓN DE RIESGO REAL (MEJORA 2) ===
# Criterio: se considera riesgo real cuando el caudal PROMEDIO del ensamble
# (no el miembro más extremo) supera el periodo de retorno de 2 años durante
# al menos 2 días consecutivos. Así un solo pico aislado de un miembro del
# ensamble no dispara falsas alarmas.
DIAS_MINIMOS = 2
RP_MINIMO = 2

def evaluar_riesgo(pron, rp_dict):
    col = next((c for c in ('flow_avg', 'flow_med') if c in pron.columns), pron.columns[0])
    diario = pron[col].resample('D').mean()
    pico = diario.max()
    fecha_pico = diario.idxmax()

    # Nivel más alto de periodo de retorno superado por el pico promedio
    nivel = 0
    for rp, q in sorted(rp_dict.items()):
        if pico >= q:
            nivel = rp

    # Días consecutivos por encima del umbral mínimo
    q_min = rp_dict.get(RP_MINIMO)
    consecutivos, maximo_consecutivo = 0, 0
    if q_min is not None:
        for v in diario:
            consecutivos = consecutivos + 1 if v >= q_min else 0
            maximo_consecutivo = max(maximo_consecutivo, consecutivos)

    hay_riesgo = (nivel >= RP_MINIMO) and (maximo_consecutivo >= DIAS_MINIMOS)
    return hay_riesgo, pico, fecha_pico, nivel, maximo_consecutivo, col

hay_riesgo, pico, fecha_pico, nivel, dias_sobre, col_usada = evaluar_riesgo(pronostico, rp_dict)

